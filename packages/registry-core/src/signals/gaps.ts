export async function fetchGaps(
  zips: string[],
  keywords: string[],
  httpOpts: FetchRetryOptions = {}
): Promise<GapRow[]> {
  const rows: GapRow[] = [];

  for (const zip of zips) {
    const population = CO_ZIP_POPULATION[zip] ?? 0;
    for (const kw of keywords) {
      const url = buildSoqlUrl(`${SOCRATA_BASE}/${ENTITY_DATASET_ID}.json`, {
        $select: "count(*)",
        $where: [
          `${ENTITY_FIELDS.zipCode}='${zip}'`,
          `${ENTITY_FIELDS.status}='Good Standing'`,
          `upper(${ENTITY_FIELDS.name}) like '%${kw.toUpperCase()}%'`,
        ].join(" AND "),
      });
      const resp = await fetchWithRetry(url, httpOpts);
      const data = (await resp.json()) as Array<Record<string, unknown>>;
      const first = data[0];
      const count = parseInt(String(first?.["count"] ?? "0"), 10);
      rows.push({
        zipCode: zip,
        keyword: kw,
        entityCount: count,
        population,
        density: population > 0 ? (count / population) * 1000 : 0,
      });
    }
  }
  return rows;
}
